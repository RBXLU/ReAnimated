package com.pycodder.reanimated.api;

/**
 * Кнопка расширения в настройках ReAnimated. Появляется отдельной секцией
 * «Расширения» — там же, где студия и редактор профиля.
 *
 * Экран, который откроет кнопка, мод создаёт сам: {@link #open(Object)} получает
 * текущий экран настроек как {@code Object} (это {@code Screen} нужной версии) —
 * его удобно передать своему экрану как родителя.
 */
public interface SettingsEntry {

    /** Идентификатор вида {@code modid:name} — по нему кнопка не задваивается. */
    String id();

    /** Надпись на кнопке. Обычный текст, а не ключ перевода — расширение переводит само. */
    String label();

    /** Нажатие. {@code parent} — экран настроек ReAnimated, с которого её нажали. */
    void open(Object parent);
}
