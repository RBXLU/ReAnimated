package com.pycodder.reanimated.api;

/**
 * Правило «анимировать ли этот экран», добавленное другим модом.
 *
 * Нужно там, где мод ReAnimated не может знать деталей чужого экрана: экран сам
 * рисует свою анимацию, держит кадровый буфер, ломается от смещённой матрицы или,
 * наоборот, специально хочет анимироваться, хотя игрок отключил анимацию модовых
 * экранов. Вместо того чтобы ждать правку в самом ReAnimated, автор экрана ставит
 * своё правило.
 *
 * Правила спрашиваются в порядке регистрации; первый определённый ответ побеждает,
 * а настройки игрока для конкретного экрана всё равно сильнее любого правила.
 */
public interface AnimationFilter {

    enum Result {
        /** Правило ничего не решает — спрашиваем дальше. */
        DEFAULT,
        /** Анимировать этот экран. */
        ANIMATE,
        /** Не трогать этот экран. */
        SKIP
    }

    Result test(Object screen);
}
